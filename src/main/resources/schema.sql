-- Modelo do dbdiagram. "user" é palavra reservada no Postgres, por isso a tabela chama "users".
CREATE TABLE IF NOT EXISTS category (
    id_category   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          TEXT NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS ingredient (
    id_ingredient INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          TEXT NOT NULL UNIQUE,
    category      INT NOT NULL REFERENCES category (id_category)
);

-- image_url, difficulty, meal_type e steps não estão no diagrama, mas o app precisa deles.
CREATE TABLE IF NOT EXISTS recipe (
    id_recipe     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          TEXT NOT NULL UNIQUE,
    description   TEXT NOT NULL,
    prep_time     FLOAT NOT NULL,
    image_url     TEXT,
    difficulty    TEXT,
    meal_type     TEXT,
    steps         TEXT
);

CREATE TABLE IF NOT EXISTS recipe_ingredient (
    id_recipe     INT NOT NULL REFERENCES recipe (id_recipe),
    id_ingredient INT NOT NULL REFERENCES ingredient (id_ingredient),
    quantity      FLOAT NOT NULL,
    measure_unity TEXT NOT NULL,
    PRIMARY KEY (id_recipe, id_ingredient)
);

CREATE TABLE IF NOT EXISTS goal (
    id_goal       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    goal_name     TEXT NOT NULL UNIQUE
);

-- id_goal: relação user–goal desenhada no diagrama.
CREATE TABLE IF NOT EXISTS users (
    id_user       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          TEXT NOT NULL UNIQUE,
    password      TEXT NOT NULL,
    id_goal       INT REFERENCES goal (id_goal)
);

CREATE TABLE IF NOT EXISTS preference (
    id_preference   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    preference_name TEXT NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS user_preference (
    id_user       INT NOT NULL REFERENCES users (id_user) ON DELETE CASCADE,
    id_preference INT NOT NULL REFERENCES preference (id_preference),
    PRIMARY KEY (id_user, id_preference)
);

CREATE TABLE IF NOT EXISTS restriction (
    id_restriction   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restriction_name TEXT NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS user_restriction (
    id_user        INT NOT NULL REFERENCES users (id_user) ON DELETE CASCADE,
    id_restriction INT NOT NULL REFERENCES restriction (id_restriction),
    PRIMARY KEY (id_user, id_restriction)
);
